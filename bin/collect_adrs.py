#!/usr/bin/env python3
"""Copy the ADRs of the sibling repositories into docs/adr/ for publication.

The copies are committed, so the docs build needs no access to those repositories,
several of which are internal. Re-run this after pulling the sibling repos:

    make update-git-repos
    make collect-adrs
"""

import re
import shutil
import subprocess
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "docs" / "adr"
MKDOCS = ROOT / "mkdocs.yml"
NAV_START = "      # adr-sources-start"
NAV_END = "      # adr-sources-end"
SOURCES = ROOT / "git-repos.txt"
ADR_DIRS = ("docs/adr", "doc/adr")

# `* Status: accepted` and `- **Status:** proposed` are both in use.
META = re.compile(r"^[*-]\s+\*{0,2}(status|date)\*{0,2}:?\*{0,2}\s*(.*)$", re.I | re.M)


def git(repo_dir, *args):
    result = subprocess.run(
        ["git", "-C", str(repo_dir), *args],
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        text=True,
    )
    return result.stdout.strip() if result.returncode == 0 else None


def adr_source(repo_dir):
    for candidate in ADR_DIRS:
        path = repo_dir / candidate
        if path.is_dir():
            return path
    return None


def heading(path):
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return path.stem


def meta(path, key):
    text = path.read_text(encoding="utf-8")
    for found in META.finditer(text):
        if found.group(1).lower() == key:
            return found.group(2).strip().strip("*").strip()
    return ""


def yaml_scalar(value):
    return "'" + value.replace("'", "''") + "'"


def copy_repo(repo):
    """Copy one repository's ADR directory into docs/adr/<repo>."""
    repo_dir = ROOT / repo
    source = adr_source(repo_dir)
    destination = TARGET / repo

    if destination.exists():
        shutil.rmtree(destination)

    if source is None:
        return []

    shutil.copytree(source, destination)

    sha = git(repo_dir, "rev-parse", "--short", "HEAD")
    source_path = source.relative_to(repo_dir).as_posix()
    today = date.today().isoformat()
    for path in sorted(destination.rglob("*.md")):
        origin = path.relative_to(destination).as_posix()
        link = f"https://github.com/statisticsnorway/{repo}/blob/{sha}/{source_path}/{origin}"
        label = f"statisticsnorway/{repo}" + (f"@{sha}" if sha else "")
        with open(path, "a", encoding="utf-8") as file:
            file.write(
                f"\n\n---\n\n*Copied from [{label}]({link}) on {today} by "
                "`make collect-adrs`. The canonical version is maintained in that "
                "repository.*\n"
            )

    return [
        {"path": path, "repo": repo, "origin": source_path, "sha": sha}
        for path in sorted(destination.rglob("*.md"))
    ]


def own_adrs():
    return sorted(p for p in TARGET.glob("*.md") if p.name != "index.md")


def write_index(copied):
    lines = [
        "<!-- Generated by `make collect-adrs`; edit bin/collect_adrs.py instead. -->",
        "",
        "# Architecture decision records",
        "",
        "Architecture decisions for the Metadata System. ADRs of this repository are",
        "authored here; the rest are snapshots copied from the sibling repositories by",
        "`make collect-adrs`, so the canonical copy lives in the source repository.",
        "",
        "## This repository",
        "",
    ]
    for path in own_adrs():
        lines.append(f"- [{heading(path)}]({path.name})")

    by_repo = {}
    for entry in copied:
        by_repo.setdefault(entry["repo"], []).append(entry)

    for repo, entries in by_repo.items():
        sha = entries[0]["sha"]
        snapshot = (
            f"Snapshot of [statisticsnorway/{repo}@{sha}]"
            f"(https://github.com/statisticsnorway/{repo}/tree/{sha}/{entries[0]['origin']})."
            if sha
            else f"Snapshot of `{repo}`."
        )
        lines += ["", f"## {repo}", "", snapshot, ""]
        for entry in entries:
            details = [d for d in (meta(entry["path"], "status"), meta(entry["path"], "date")) if d]
            suffix = f" — *{'*, *'.join(details)}*" if details else ""
            link = entry["path"].relative_to(TARGET).as_posix()
            lines.append(f"- [{heading(entry['path'])}]({link}){suffix}")

    (TARGET / "index.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_nav(copied):
    by_repo = {}
    for entry in copied:
        by_repo.setdefault(entry["repo"], []).append(entry)

    block = [NAV_START]
    for repo, entries in by_repo.items():
        block.append(f"      - {yaml_scalar(repo)}:")
        for entry in entries:
            # Backticks are literal text in a nav label, so drop them.
            label = heading(entry["path"]).replace("`", "")
            block.append(
                f"          - {yaml_scalar(label)}: "
                f"{yaml_scalar('adr/' + entry['path'].relative_to(TARGET).as_posix())}"
            )
    block.append(NAV_END)
    generated = "\n".join(block)

    text = MKDOCS.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(NAV_START) + r".*?" + re.escape(NAV_END), re.DOTALL)
    if not pattern.search(text):
        raise SystemExit(f"mkdocs.yml is missing the {NAV_START.strip()} / {NAV_END.strip()} markers")
    MKDOCS.write_text(pattern.sub(lambda _: generated, text), encoding="utf-8")


def main():
    repos = [line.strip() for line in SOURCES.read_text(encoding="utf-8").splitlines() if line.strip()]
    copied = []
    for repo in repos:
        if not (ROOT / repo).is_dir():
            print(f"  {repo}: not cloned, skipped")
            continue
        entries = copy_repo(repo)
        if entries:
            print(f"  {repo}: {len(entries)} ADR(s)")
            copied += entries

    write_index(copied)
    write_nav(copied)
    print(f"Wrote {len(own_adrs())} own and {len(copied)} copied ADR(s) to docs/adr/")


if __name__ == "__main__":
    main()
